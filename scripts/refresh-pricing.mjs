#!/usr/bin/env node
/**
 * Refresh the frontier model snapshot in index.html from OpenRouter.
 *
 * For each model family below, picks the newest matching model on OpenRouter
 * (by the API's `created` timestamp) and records its current list prices.
 *
 * Usage:
 *   node scripts/refresh-pricing.mjs          # preview changes (dry run)
 *   node scripts/refresh-pricing.mjs --write  # update index.html
 *   node scripts/refresh-pricing.mjs --check  # exit 1 if index.html is stale
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const INDEX_PATH = path.join(ROOT, 'index.html');
const MODELS_URL = 'https://openrouter.ai/api/v1/models';

const START_MARKER = '  // BEGIN FRONTIER_PRICING';
const END_MARKER = '  // END FRONTIER_PRICING';

/**
 * Frontier model families shown in the calculator, in display order.
 *
 * `pattern` matches the OpenRouter model id. Keep it narrow enough to exclude
 * batch, free, and experimental variants. When a provider renames a family,
 * update its pattern here -- the newest matching model is selected automatically.
 */
const FAMILIES = [
  { label: 'Anthropic Claude Opus', pattern: /^anthropic\/claude-opus-[\d.]+$/, checked: true },
  { label: 'Anthropic Claude Sonnet', pattern: /^anthropic\/claude-sonnet-[\d.]+$/, checked: true },
  { label: 'Anthropic Claude Fable', pattern: /^anthropic\/claude-fable-[\d.]+$/, checked: true },
  { label: 'Anthropic Claude Haiku', pattern: /^anthropic\/claude-haiku-[\d.]+$/, checked: false },
  { label: 'OpenAI GPT Sol', pattern: /^openai\/gpt-[\d.]+-sol$/, checked: true },
  { label: 'OpenAI GPT Terra', pattern: /^openai\/gpt-[\d.]+-terra$/, checked: true },
  { label: 'OpenAI GPT Sol Pro', pattern: /^openai\/gpt-[\d.]+-sol-pro$/, checked: false },
  { label: 'Google Gemini Argon', pattern: /^google\/gemini-[\d.]+-argon$/, checked: false },
  { label: 'Google Gemini Flash', pattern: /^google\/gemini-[\d.]+-flash$/, checked: false },
  { label: 'xAI Grok', pattern: /^x-ai\/grok-[\d.]+$/, checked: false },
  { label: 'Amazon Nova Premier', pattern: /^amazon\/nova-premier-v[\d.]+$/, checked: false },
  { label: 'Cohere Command A Plus', pattern: /^cohere\/command-a-plus$/, checked: false },
];

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

// Cached input prices can be sub-cent, so they keep 3 decimals; all other
// prices round to 2.
function perMillion(value, decimals = 2) {
  const n = parseFloat(value);
  if (!Number.isFinite(n) || n < 0) return null;
  return roundPrice(n * 1e6, decimals);
}

function roundPrice(n, decimals = 2) {
  if (n === 0) return 0;
  const factor = Math.pow(10, decimals);
  return Math.round(n * factor) / factor;
}

function quote(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function displayName(model) {
  return String(model.name || model.id).replace(/^[^:]+:\s*/, '').trim();
}

function pickModels(payload) {
  const models = payload.data || payload;
  if (!Array.isArray(models)) fail('unexpected OpenRouter response: missing data array');

  return FAMILIES.map(family => {
    const candidates = models
      .filter(m => family.pattern.test(m.id))
      .sort((a, b) => (Number(b.created) || 0) - (Number(a.created) || 0));

    if (candidates.length === 0) {
      fail(`no OpenRouter model matched ${family.label} (${family.pattern}). Update FAMILIES in scripts/refresh-pricing.mjs.`);
    }

    const model = candidates[0];
    const inputPrice = perMillion(model.pricing?.prompt);
    const cachedPrice = perMillion(model.pricing?.input_cache_read, 3) ?? inputPrice;
    const outputPrice = perMillion(model.pricing?.completion);

    if (inputPrice === null || cachedPrice === null || outputPrice === null) {
      fail(`missing pricing for ${model.id}`);
    }

    return {
      id: model.id,
      name: displayName(model),
      inputPrice,
      cachedPrice,
      outputPrice,
      checked: family.checked,
      created: Number(model.created) || 0,
    };
  });
}

function renderBlock(models, today) {
  const lines = models.map(m =>
    `    { id: ${quote(m.id)}, name: ${quote(m.name)}, inputPrice: ${m.inputPrice}, cachedPrice: ${m.cachedPrice}, outputPrice: ${m.outputPrice}, checked: ${m.checked} },`
  );

  return [
    START_MARKER,
    `  // Snapshot: ${today}`,
    '  // Generated by scripts/refresh-pricing.mjs from https://openrouter.ai/api/v1/models.',
    '  // Prices are USD per 1M tokens. The app refreshes them live at load time; these are the offline fallback.',
    '  const FRONTIER_MODELS = [',
    ...lines,
    '  ];',
    END_MARKER,
  ].join('\n');
}

function extractBlock(html) {
  const start = html.indexOf(START_MARKER);
  const end = html.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) {
    fail('index.html is missing the FRONTIER_PRICING marker block');
  }
  return { start, end: end + END_MARKER.length, text: html.slice(start, end + END_MARKER.length) };
}

function normalizeSnapshot(text) {
  return text.replace(/^  \/\/ Snapshot: \d{4}-\d{2}-\d{2}$/m, '  // Snapshot: YYYY-MM-DD');
}

function formatPrice(n, decimals = 2) {
  return `$${n.toFixed(decimals)}`;
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const write = args.has('--write');
  const check = args.has('--check');

  const response = await fetch(MODELS_URL, {
    headers: { Accept: 'application/json' },
  });
  if (!response.ok) fail(`OpenRouter returned HTTP ${response.status}`);

  const payload = await response.json();
  const models = pickModels(payload);
  const today = new Date().toISOString().slice(0, 10);
  const nextBlock = renderBlock(models, today);

  const html = await readFile(INDEX_PATH, 'utf8');
  const current = extractBlock(html);
  const stale = normalizeSnapshot(current.text) !== normalizeSnapshot(nextBlock);

  console.log(`Frontier pricing snapshot (${today})`);
  for (const m of models) {
    console.log(
      `  ${m.name.padEnd(26)} ${m.id.padEnd(38)} ` +
      `in ${formatPrice(m.inputPrice).padStart(8)}  ` +
      `cached ${formatPrice(m.cachedPrice, 3).padStart(8)}  ` +
      `out ${formatPrice(m.outputPrice).padStart(8)}`
    );
  }

  if (check) {
    if (stale) {
      console.error('\nindex.html is stale. Run: node scripts/refresh-pricing.mjs --write');
      process.exit(1);
    }
    console.log('\nindex.html is up to date.');
    return;
  }

  if (!stale) {
    console.log('\nNo changes needed.');
    return;
  }

  const nextHtml = html.slice(0, current.start) + nextBlock + html.slice(current.end);

  if (write) {
    await writeFile(INDEX_PATH, nextHtml);
    console.log(`\nUpdated ${path.relative(process.cwd(), INDEX_PATH)}`);
  } else {
    console.log('\nDry run. Re-run with --write to apply. Proposed block:\n');
    console.log(nextBlock);
  }
}

main().catch(error => fail(error.stack || error.message));
